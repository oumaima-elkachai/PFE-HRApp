export function BasculeLangue({ className = '' }: { className?: string }) {
  const { langue, definir, t } = useI18n();
  const codes = Object.keys(LANGUES) as Langue[];

  return (
    <div
      role="group"
      aria-label={t('nav.langue')}
      className={'inline-flex items-center gap-0.5 rounded-xl border '
        + 'border-stone-200 bg-stone-100 p-0.5 ' + className}
    >
      {codes.map((c) => (
        <button
          key={c}
          type="button"
          onClick={() => definir(c)}
          aria-pressed={langue === c}
          title={LANGUES[c].nom}
          className={'px-2.5 py-1 text-[11px] font-bold rounded-lg transition-colors '
            + (langue === c
              ? 'text-white bg-brand-500'
              : 'text-stone-500 hover:text-stone-800')}
        >
          {LANGUES[c].court}
        </button>
      ))}
    </div>
  );
}