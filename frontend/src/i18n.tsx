// src/i18n.tsx
//
// Traduction français / anglais / arabe, sans dépendance.
//
// ── Pourquoi pas react-i18next ─────────────────────────────────────
//
// À deux jours de l'échéance, ajouter une bibliothèque avec sa
// configuration, son chargement asynchrone et son interpolation coûte
// plus de temps à brancher qu'à écrire. Ce fichier fait les cinq
// choses dont l'application a besoin — chercher une clé, se replier
// sur le français, remplacer {nom}, mettre au pluriel, formater dates
// et nombres — en une page qu'on peut lire en entier.
//
// ── L'arabe et l'écriture droite-à-gauche ──────────────────────────
//
// Le fournisseur pose « dir » et « lang » sur <html>. Tailwind traduit
// alors ms-* et me-* correctement, mais PAS ml-* et mr-* : ceux-là
// sont physiques et ne se retournent pas. Les pages refaites utilisent
// les propriétés logiques ; les autres resteront d'aplomb en français
// et en anglais, et montreront quelques décalages en arabe.
//
// C'est une limite connue, pas une surprise : la dire vaut mieux que
// la découvrir pendant la démonstration.
//
// ── Couverture ─────────────────────────────────────────────────────
//
// Une clé absente retombe sur le français plutôt que de disparaître.
// Une page non traduite reste donc utilisable — elle n'est simplement
// pas traduite, et rien ne casse.

