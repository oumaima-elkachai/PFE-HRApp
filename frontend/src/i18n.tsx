export type Cle = keyof typeof FR;

const DICOS: Record<Langue, Partial<Record<Cle, string>>> = { fr: FR, en: EN, ar: AR };

function langueMemorisee(): Langue {
  try {
    const v = localStorage.getItem(CLE);
    if (v === 'fr' || v === 'en' || v === 'ar') return v;
  } catch { /* stockage indisponible */ }

  // La langue du navigateur, mais seulement si on la gère. Un
  // navigateur en allemand obtient le français, pas une page vide.
  const n = typeof navigator !== 'undefined' ? navigator.language : '';
  if (n.startsWith('ar')) return 'ar';
  if (n.startsWith('en')) return 'en';
  return 'fr';
}

interface Valeurs { [nom: string]: string | number }

interface Contexte {
  langue: Langue;
  dir: 'ltr' | 'rtl';
  definir: (l: Langue) => void;
  /** Traduit une clé. Les valeurs remplacent les {marqueurs}. */
  t: (cle: Cle, valeurs?: Valeurs) => string;
  /** Pluriel : utilise « <cle>_pluriel » quand la langue l'exige. */
  tn: (cle: Cle, n: number) => string;
  fmt: {
    date: (d: Date | string, options?: Intl.DateTimeFormatOptions) => string;
    heure: (d: Date | string) => string;
    nombre: (n: number, options?: Intl.NumberFormatOptions) => string;
  };
}

const Ctx = createContext<Contexte | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [langue, setLangue] = useState<Langue>(langueMemorisee);
  const dir = LANGUES[langue].dir;

  useEffect(() => {
    document.documentElement.lang = langue;
    document.documentElement.dir = dir;
    try { localStorage.setItem(CLE, langue); } catch { /* sans gravité */ }
  }, [langue, dir]);

  const t = useCallback((cle: Cle, valeurs?: Valeurs) => {
    // Repli en cascade : la langue active, puis le français, puis la
    // clé elle-même. Afficher la clé est laid, mais c'est visible —
    // une chaîne vide se confond avec un bug de mise en page.
    const brut = DICOS[langue][cle] ?? FR[cle] ?? cle;
    if (!valeurs) return brut;
    return brut.replace(/\{(\w+)\}/g, (entier, nom) =>
      (nom in valeurs ? String(valeurs[nom]) : entier));
  }, [langue]);

  const tn = useCallback((cle: Cle, n: number) => {
    const pluriel = `${cle}_pluriel` as Cle;

    // Les trois langues ne coupent pas au même endroit : le français
    // met au singulier à zéro (« 0 jour »), l'anglais au pluriel
    // (« 0 days »), et l'arabe emploie une forme propre au duel et aux
    // petits nombres. On approche l'arabe par « singulier pour 1,
    // pluriel sinon » — exact pour 0 et pour 3 à 10, imparfait pour le
    // duel, et bien plus lisible qu'une règle à six branches dont
    // aucune page n'a besoin ici.
    const auSingulier = langue === 'fr' ? Math.abs(n) < 2 : Math.abs(n) === 1;
    const choisie = auSingulier ? cle : pluriel;
    const existe = DICOS[langue][choisie] ?? FR[choisie];
    return t(existe ? choisie : cle, { n });
  }, [langue, t]);

  const locale = LANGUES[langue].locale;
  const fmt = {
    date: (d: Date | string, options?: Intl.DateTimeFormatOptions) =>
      new Date(d).toLocaleDateString(locale,
        options ?? { day: 'numeric', month: 'long', year: 'numeric' }),
    heure: (d: Date | string) =>
      new Date(d).toLocaleTimeString(locale, { hour: '2-digit', minute: '2-digit' }),
    nombre: (n: number, options?: Intl.NumberFormatOptions) =>
      new Intl.NumberFormat(locale, options).format(n),
  };

  return (
    <Ctx.Provider value={{ langue, dir, definir: setLangue, t, tn, fmt }}>
      {children}
    </Ctx.Provider>
  );
}

export function useI18n(): Contexte {
  const c = useContext(Ctx);
  if (!c) throw new Error('useI18n doit être utilisé dans <I18nProvider>');
  return c;
}

